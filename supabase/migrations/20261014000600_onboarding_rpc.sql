-- Task 8: the organization onboarding RPC.
--
-- private.create_organization_with_owner is the ONLY path that bootstraps an
-- organization, and that is a structural decision rather than a convention. RLS
-- policies on organizations and organization_memberships will require the caller
-- to already be a member of the organization, so there is no policy under which a
-- newcomer could insert the first membership - the chicken-and-egg problem. This
-- one function runs as its definer, creates the organization, the caller's active
-- membership, the first clinic, the organization-scoped role set and the owner's
-- assignment, and returns the organization id. Every insert happens inside the
-- caller's transaction, so a failure anywhere leaves nothing behind: no orphan
-- organization, no membership with no organization.
--
-- The role seed below is GENERATED from lib/permissions/registry.ts and inlined
-- rather than applied by a script, exactly as 00400 does for the platform scope,
-- with the organization id left as the plpgsql variable v_org_id so it can be
-- stamped at run time. tests/unit/onboarding-seed.test.ts fails if the inlined
-- block drifts from what the generator emits. Organization roles are seeded HERE
-- and nowhere else - never globally - so this is the single path by which a
-- tenant's role set can come into existence.
--
-- The owner assignment is ORG-WIDE (clinic_id NULL). An owner administers the
-- organization rather than one clinic, and private.clinic_ids would hand them
-- every clinic in the organization anyway through its no-scoping fallback; being
-- explicit here keeps the reach readable from the assignment row alone.

